/**
 * 한국어 별자리 이름으로 그림 데이터를 찾는다.
 * 황도 12궁이면 원소·지배성 같은 정보가 함께 들어 있고, 나머지는 계절 정보만 있다.
 */
export function getConstellationShape(koreanName) {
  const zodiac = ZODIAC_SIGNS.find((s) => s.name === koreanName)
  if (zodiac) return zodiac

  const extra = EXTRA_SHAPES.find((s) => s.name === koreanName)
  if (extra) return extra

  return null
}

